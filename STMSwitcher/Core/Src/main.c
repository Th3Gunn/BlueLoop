/**
 * @brief Sends a byte to the 74HC595 shift register using SPI1
 */
void Update_Relays(uint8_t state)
{
    // Transmit data via SPI (SER -> PA7, SRCLK -> PA5)
    HAL_SPI_Transmit(&hspi1, &state, 1, HAL_MAX_DELAY);

    // Latch the data to the outputs (RCLK -> PA4)
    HAL_GPIO_WritePin(GPIOA, GPIO_PIN_4, GPIO_PIN_SET);
    // Brief delay to ensure latch pin registers high
    for(volatile int i=0; i<100; i++);
    HAL_GPIO_WritePin(GPIOA, GPIO_PIN_4, GPIO_PIN_RESET);
}

/**
 * @brief Basic MIDI parser for Program Change messages
 */
void MIDI_Process_Byte(uint8_t byte)
{
    static uint8_t midi_state = 0;
    static uint8_t status_byte = 0;

    // Check if it's a Status Byte (MSB is 1)
    if (byte >= 0x80)
    {
        status_byte = byte;
        // Check if Program Change (0xCn, where n is channel 0-F)
        if ((status_byte & 0xF0) == 0xC0)
        {
            midi_state = 1; // Expect 1 data byte for PC
        }
        else
        {
            midi_state = 0; // Ignore other messages for now
        }
    }
    // Data byte processing
    else
    {
        if (midi_state == 1 && (status_byte & 0xF0) == 0xC0)
        {
            // Program Change Data Received (Value 0-127)
            current_relay_state = byte;
            Update_Relays(current_relay_state); // Set relays directly to PC value for test

            // Update OLED Display
            ssd1306_Fill(Black);
            ssd1306_SetCursor(2, 10);
            ssd1306_WriteString("MIDI PC Received", Font_7x10, White);

            sprintf(display_buf, "Preset: %d", byte);
            ssd1306_SetCursor(2, 35);
            ssd1306_WriteString(display_buf, Font_11x18, White);
            ssd1306_UpdateScreen();

            midi_state = 0; // Reset state machine
        }
    }
}

/**
 * @brief UART RX Interrupt Callback
 */
void HAL_UART_RxCpltCallback(UART_HandleTypeDef *huart)
{
    if (huart->Instance == USART1)
    {
        // Process incoming MIDI byte
        MIDI_Process_Byte(midi_rx_byte);
        // Start listening for the next byte
        HAL_UART_Receive_IT(&huart1, &midi_rx_byte, 1);
    }
}
